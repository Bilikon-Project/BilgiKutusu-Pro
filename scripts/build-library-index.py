#!/usr/bin/env python3
# Generate safe, static directory pages for the BilgiKutusu file library.

from __future__ import annotations

import argparse
import html
import os
import sys
from pathlib import Path
from urllib.parse import quote

MARKER = "<!-- Generated by build-library-index.py; do not edit this file. -->"
OUTPUT_NAME = "bilgikutusu-index.html"


def human_size(size: int) -> str:
    value = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} TB"


def page_for(directory: Path, root: Path) -> str:
    relative = directory.relative_to(root)
    parts = [quote(part, safe="") for part in relative.parts]
    base_url = "/kutuphane/" + ("/".join(parts) + "/" if parts else "")
    title = " / ".join(relative.parts) if relative.parts else "Bilgi Kütüphanesi"

    entries = []
    try:
        with os.scandir(directory) as scan:
            for entry in scan:
                if entry.name.startswith(".") or entry.name == OUTPUT_NAME:
                    continue
                try:
                    if entry.is_dir(follow_symlinks=False):
                        entries.append((0, entry.name.casefold(), entry.name, True, 0))
                    elif entry.is_file(follow_symlinks=False):
                        entries.append((1, entry.name.casefold(), entry.name, False, entry.stat(follow_symlinks=False).st_size))
                except OSError:
                    continue
    except OSError as error:
        raise RuntimeError(f"{directory}: {error}") from error

    entries.sort(key=lambda item: (item[0], item[1]))
    rows = []
    if relative.parts:
        rows.append('<li class="parent"><a href="../">← Üst klasör</a></li>')

    for _, _, name, is_dir, size in entries:
        href = base_url + quote(name, safe="") + ("/" if is_dir else "")
        label = html.escape(name)
        kind = "Klasör" if is_dir else human_size(size)
        symbol = "▰" if is_dir else "▤"
        rows.append(
            f'<li><a href="{html.escape(href, quote=True)}">'
            f'<span class="item-name"><span aria-hidden="true">{symbol}</span>{label}</span>'
            f'<span class="item-meta">{kind}</span></a></li>'
        )

    content = "\n".join(rows) if rows else '<li class="empty">Bu klasörde henüz içerik yok.</li>'
    safe_title = html.escape(title)
    return f'''<!doctype html>
<html lang="tr">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#101b24">
  <title>{safe_title} · BilgiKutusu Pro</title>
  <style>
    :root {{ color-scheme: dark; font-family: system-ui, sans-serif; background: #0b1218; color: #e8f0f2; }}
    * {{ box-sizing: border-box; }}
    body {{ margin: 0; padding: 36px 18px; }}
    main {{ width: min(760px, 100%); margin: auto; }}
    a {{ color: inherit; text-decoration: none; }}
    .brand {{ color: #75dfc2; font-size: .8rem; font-weight: 800; letter-spacing: .12em; }}
    h1 {{ margin: 10px 0 4px; font-size: clamp(1.7rem, 5vw, 2.5rem); overflow-wrap: anywhere; }}
    .path {{ color: #91a4ad; font-size: .85rem; margin-bottom: 24px; overflow-wrap: anywhere; }}
    ul {{ list-style: none; margin: 0; padding: 0; border: 1px solid #263844; border-radius: 14px; overflow: hidden; }}
    li + li {{ border-top: 1px solid #263844; }}
    li a {{ min-height: 56px; display: flex; align-items: center; justify-content: space-between; gap: 16px; padding: 12px 16px; }}
    li a:hover {{ background: #162a30; }}
    .item-name {{ display: flex; align-items: center; gap: 12px; overflow-wrap: anywhere; }}
    .item-name span {{ color: #75dfc2; }}
    .item-meta {{ flex: 0 0 auto; color: #91a4ad; font-size: .75rem; }}
    .parent a {{ color: #75dfc2; }}
    .empty {{ padding: 24px; color: #91a4ad; }}
    footer {{ margin-top: 20px; color: #71858e; font-size: .75rem; }}
  </style>
</head>
<body>
  <main>
    <a class="brand" href="/">BİLGİKUTUSU PRO</a>
    <h1>{safe_title}</h1>
    <p class="path">/kutuphane/{html.escape("/".join(relative.parts))}</p>
    <ul>{content}</ul>
    <footer>Çevrimdışı bilgi kütüphanesi</footer>
  </main>
</body>
</html>
'''


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate static index pages for the local library.")
    parser.add_argument(
        "library",
        nargs="?",
        type=Path,
        default=Path("/mnt/BilgiKutusu"),
        help="Kütüphane kök dizini (varsayılan: /mnt/BilgiKutusu)",
    )
    args = parser.parse_args()
    root = args.library.expanduser().resolve()

    if not root.is_dir():
        print(f"Kütüphane dizini bulunamadı: {root}", file=sys.stderr)
        return 1

    generated = skipped = 0
    for current, dirs, _ in os.walk(root, followlinks=False):
        current_path = Path(current)
        dirs[:] = sorted(
            name for name in dirs
            if not name.startswith(".") and not (current_path / name).is_symlink()
        )
        output = current_path / OUTPUT_NAME

        if output.is_symlink():
            print(f"Atlandı (sembolik bağlantı korunuyor): {output}", file=sys.stderr)
            skipped += 1
            continue
        if output.exists() and MARKER not in output.read_text(encoding="utf-8", errors="replace"):
            print(f"Atlandı (mevcut dosya korunuyor): {output}", file=sys.stderr)
            skipped += 1
            continue

        temporary = current_path / f".{OUTPUT_NAME}.{os.getpid()}.tmp"
        try:
            temporary.write_text(MARKER + "\n" + page_for(current_path, root), encoding="utf-8")
            os.replace(temporary, output)
            generated += 1
        except OSError as error:
            print(f"Oluşturulamadı: {output}: {error}", file=sys.stderr)
            try:
                temporary.unlink(missing_ok=True)
            except OSError:
                pass
            return 1

    print(f"{generated} klasör için katalog sayfası oluşturuldu; {skipped} mevcut sayfa korundu.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
